package org.apz.wallet.proof

import org.json.JSONObject
import java.math.BigInteger
import java.net.HttpURLConnection
import java.net.URL

data class NativeVerification(
    val ok: Boolean,
    val reason: String,
    val chainId: String?,
    val contract: String?,
    val anchorId: String?,
    val documentHash: String?
)

/**
 * Minimal JSON-RPC verifier for an EVM-compatible APZ node.
 * In production, use a maintained ABI/RPC library and strict TLS/pinning policy.
 */
class NativeChainVerifier(
    private val rpcUrl: String,
    private val contractAddress: String,
    private val expectedChainId: String
) {
    fun verifyDocumentHash(documentHash: String): NativeVerification {
        val chainId = rpc("eth_chainId", emptyList())?.optString("result")
            ?: return NativeVerification(false,"rpc_chain_id_failed",null,null,null,null)

        if (!chainId.equals(expectedChainId, true))
            return NativeVerification(false,"unexpected_chain_id",chainId,contractAddress,null,null)

        // keccak256("verifyDocument(bytes32)") first 4 bytes = 0x...
        // This placeholder selector is intentionally generated by the backend in production.
        val selector = "0xVERIFYDOCUMENT_SELECTOR"
        val data = selector + documentHash.removePrefix("0x").padStart(64,'0')

        val result = rpc("eth_call", listOf(
            JSONObject().put("to",contractAddress).put("data",data),
            "latest"
        ))?.optString("result")

        if (result == null || result == "0x")
            return NativeVerification(false,"contract_call_failed",chainId,contractAddress,null,null)

        return NativeVerification(
            ok=true,
            reason="rpc_contract_call_completed",
            chainId=chainId,
            contract=contractAddress,
            anchorId=null,
            documentHash=documentHash
        )
    }

    private fun rpc(method:String, params:List<Any>):JSONObject? {
        val conn=URL(rpcUrl).openConnection() as HttpURLConnection
        conn.requestMethod="POST"
        conn.doOutput=true
        conn.setRequestProperty("Content-Type","application/json")
        val body=JSONObject()
            .put("jsonrpc","2.0")
            .put("id",1)
            .put("method",method)
            .put("params",params)
            .toString()
        conn.outputStream.use{it.write(body.toByteArray())}
        if(conn.responseCode !in 200..299) return null
        return JSONObject(conn.inputStream.bufferedReader().use{it.readText()})
    }
}
